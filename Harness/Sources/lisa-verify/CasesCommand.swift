// `lisa-verify cases`: the catalogue, optionally one session or area.

import ArgumentParser
import Foundation
import LisaVerifyCases
import LisaVerifyKit

struct CasesCommand: ParsableCommand {
    static let configuration = CommandConfiguration(commandName: "cases", abstract: "List the cases.")

    @Option(help: "Only this session (X1 … X7, LS-1 … LS-3).") var session: String?
    @Option(help: "Only this area (NEAR, APPLE, HARNESS, …).") var area: String?
    @Flag(help: "Print Harness/docs/CASES.md (the catalogue as Markdown).") var markdown = false

    func run() throws {
        var cases = VerifyCatalogue.all
        if let session { cases = cases.filter { $0.session == session.uppercased() } }
        if let area { cases = cases.filter { $0.area == area.uppercased() } }
        if markdown {
            print(Self.markdown(cases))
            return
        }
        for verifyCase in cases {
            let place = verifyCase.session ?? "fixture"
            print("\(verifyCase.id)\t\(place)\t\(verifyCase.executor.rawValue)\t\(verifyCase.title)")
        }
        print("\(cases.count) case\(cases.count == 1 ? "" : "s")")
    }

    /// The catalogue as `Harness/docs/CASES.md`.
    static func markdown(_ cases: [VerifyCase]) -> String {
        var lines = [
            "<!-- Generated by `swift run lisa-verify cases --markdown`; do not edit by hand. -->",
            "# Owner-verification cases", "",
            "Every case of the catalogue (plan R2 §10.8), its session, executor, required result level, gate and expected "
                + "outcome. `lisa-verify guide <case>` shows its prerequisites, evidence and steps.", "",
            "| Case | Session | Executor | Level | Title | Gate | Expected outcome |", "|---|---|---|---|---|---|---|",
        ]
        for verifyCase in cases {
            let cells = [
                verifyCase.id.text, verifyCase.session ?? "fixture", verifyCase.executor.rawValue,
                verifyCase.requiredResultLevel.rawValue, verifyCase.title, verifyCase.gate, verifyCase.expectedOutcome,
            ].map { $0.replacingOccurrences(of: "|", with: "\\|") }
            lines.append("| " + cells.joined(separator: " | ") + " |")
        }
        return lines.joined(separator: "\n")
    }
}
